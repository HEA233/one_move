create or replace function public.om_start_round(
  p_session_id uuid,
  p_round_id uuid,
  p_campaign_id text,
  p_round_index integer,
  p_is_replay boolean,
  p_evidence_mode text,
  p_protocol_version text,
  p_baseline_snapshot jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  existing_round public.om_rounds%rowtype;
  created_round public.om_rounds%rowtype;
begin
  perform 1 from public.om_sessions where id = p_session_id for update;
  if not found then
    raise exception 'unauthorised' using errcode = 'P0001';
  end if;

  select * into existing_round
  from public.om_rounds
  where session_id = p_session_id
    and phase in ('choosing', 'preparing_move', 'awaiting_rechoice')
  order by round_index desc
  limit 1
  for update;

  if found then
    return jsonb_build_object('round', to_jsonb(existing_round), 'created', false);
  end if;

  insert into public.om_rounds (
    id, session_id, campaign_id, round_index, protocol_version, evidence_mode,
    phase, is_replay, baseline_snapshot
  ) values (
    p_round_id, p_session_id, p_campaign_id, p_round_index, p_protocol_version,
    p_evidence_mode, 'choosing', p_is_replay, p_baseline_snapshot
  ) returning * into created_round;

  return jsonb_build_object('round', to_jsonb(created_round), 'created', true);
end;
$$;

create or replace function public.om_initial(
  p_session_id uuid,
  p_round_id uuid,
  p_command_id uuid,
  p_expected_revision integer,
  p_request_hash text,
  p_plan jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  prior public.om_commands%rowtype;
  round_row public.om_rounds%rowtype;
begin
  select * into prior from public.om_commands where session_id = p_session_id and command_id = p_command_id;
  if found then
    if prior.action <> 'initial' or prior.request_hash <> p_request_hash or prior.round_id <> p_round_id then
      raise exception 'command_conflict' using errcode = 'P0001';
    end if;
    select * into round_row from public.om_rounds where id = prior.round_id;
    return jsonb_build_object('round', to_jsonb(round_row), 'replayed', true, 'command_id', p_command_id);
  end if;

  select * into round_row from public.om_rounds where id = p_round_id and session_id = p_session_id for update;
  if not found then raise exception 'not_found' using errcode = 'P0001'; end if;
  if round_row.revision <> p_expected_revision then raise exception 'stale_revision' using errcode = 'P0001'; end if;
  if round_row.phase <> 'choosing' then raise exception 'conflict' using errcode = 'P0001'; end if;

  update public.om_rounds set
    initial_brand = p_plan->>'initialBrand',
    target_brand = p_plan->>'targetBrand',
    reason_keys = coalesce(p_plan->'reasonKeys', '[]'::jsonb),
    other_reason = nullif(p_plan->>'protectedOther', ''),
    eligible_card_ids = coalesce(p_plan->'eligibleCardIds', '[]'::jsonb),
    excluded_cards = coalesce(p_plan->'excludedCards', '[]'::jsonb),
    considered_card_ids = coalesce(p_plan->'consideredCardIds', '[]'::jsonb),
    selection_policy = coalesce(p_plan->>'selectionPolicy', 'contextual_v2'),
    selection_policy_version = coalesce(p_plan->>'selectionPolicyVersion', 'contextual_v2'),
    requested_selector = coalesce(p_plan->>'requestedSelector', 'curated'),
    selection_probability = nullif(p_plan->>'selectionProbability', '')::numeric,
    assignment_probability_meaning = p_plan->>'assignmentProbabilityMeaning',
    fallback_note = p_plan->'fallbackNote',
    phase = 'preparing_move',
    revision = revision + 1,
    updated_at = now()
  where id = p_round_id;

  insert into public.om_commands(session_id, round_id, command_id, action, request_hash)
    values (p_session_id, p_round_id, p_command_id, 'initial', p_request_hash);
  select * into round_row from public.om_rounds where id = p_round_id;
  return jsonb_build_object('round', to_jsonb(round_row), 'replayed', false, 'command_id', p_command_id);
end;
$$;

create or replace function public.om_ensure_move(
  p_session_id uuid,
  p_round_id uuid,
  p_command_id uuid,
  p_expected_revision integer,
  p_request_hash text,
  p_plan jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  prior public.om_commands%rowtype;
  round_row public.om_rounds%rowtype;
begin
  select * into prior from public.om_commands where session_id = p_session_id and command_id = p_command_id;
  if found then
    if prior.action <> 'ensure_move' or prior.request_hash <> p_request_hash or prior.round_id <> p_round_id then raise exception 'command_conflict' using errcode = 'P0001'; end if;
