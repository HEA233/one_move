create or replace function public.om_again(
  p_session_id uuid,
  p_round_id uuid,
  p_command_id uuid,
  p_expected_revision integer,
  p_request_hash text,
  p_next_round_id uuid,
  p_next_round_index integer,
  p_next_campaign_id text,
  p_next_evidence_mode text,
  p_next_baseline_snapshot jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  prior public.om_commands%rowtype;
  old_round public.om_rounds%rowtype;
  next_round public.om_rounds%rowtype;
begin
  select * into prior from public.om_commands where session_id = p_session_id and command_id = p_command_id;
  if found then
    if prior.action <> 'again' or prior.request_hash <> p_request_hash or prior.round_id <> p_round_id then raise exception 'command_conflict' using errcode = 'P0001'; end if;
    select * into old_round from public.om_rounds where id = prior.round_id;
    select * into next_round from public.om_rounds where id = prior.result_round_id;
    return jsonb_build_object('old_round', to_jsonb(old_round), 'next_round', to_jsonb(next_round), 'replayed', true, 'command_id', p_command_id);
