  if old_round.revision <> p_expected_revision then raise exception 'stale_revision' using errcode = 'P0001'; end if;
  if old_round.phase not in ('finished', 'aborted') then raise exception 'conflict' using errcode = 'P0001'; end if;

  insert into public.om_rounds(id, session_id, campaign_id, round_index, protocol_version, evidence_mode, phase, is_replay, baseline_snapshot)
    values (p_next_round_id, p_session_id, p_next_campaign_id, p_next_round_index, old_round.protocol_version, p_next_evidence_mode, 'choosing', true, p_next_baseline_snapshot)
    returning * into next_round;
  insert into public.om_commands(session_id, round_id, result_round_id, command_id, action, request_hash)
    values (p_session_id, p_round_id, p_next_round_id, p_command_id, 'again', p_request_hash);
  return jsonb_build_object('old_round', to_jsonb(old_round), 'next_round', to_jsonb(next_round), 'replayed', false, 'command_id', p_command_id);
end;
$$;

