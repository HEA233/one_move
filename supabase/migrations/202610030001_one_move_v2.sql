create table public.om_sessions (
  id uuid primary key,
  capability_hash text not null unique,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create table public.om_rounds (
  id uuid primary key,
  session_id uuid not null references public.om_sessions(id) on delete restrict,
  campaign_id text not null,
  round_index integer not null check (round_index > 0),
  protocol_version text not null,
  evidence_mode text not null check (evidence_mode in ('recorded_pilot', 'rehearsal', 'fixture')),
  revision integer not null default 0 check (revision >= 0),
  phase text not null check (phase in ('choosing', 'preparing_move', 'awaiting_rechoice', 'finished', 'aborted')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  ended_at timestamptz,
  is_replay boolean not null default false,
  baseline_snapshot jsonb not null,
  initial_brand text check (initial_brand in ('charitea_mate_can', 'oom_balance')),
  target_brand text check (target_brand in ('charitea_mate_can', 'oom_balance')),
  reason_keys jsonb not null default '[]'::jsonb,
  other_reason text,
  eligible_card_ids jsonb not null default '[]'::jsonb,
  excluded_cards jsonb not null default '[]'::jsonb,
  considered_card_ids jsonb not null default '[]'::jsonb,
  selection_policy text not null default 'contextual_v2',
  selection_policy_version text not null default 'contextual_v2',
  requested_selector text not null default 'curated' check (requested_selector in ('curated', 'live', 'randomised')),
  selector_origin text check (selector_origin in ('curated', 'live_model', 'curated_timeout', 'curated_invalid', 'curated_unavailable')),
  selection_probability numeric,
  assignment_probability_meaning text,
  model_id text,
  prompt_version text,
  fallback_note jsonb,
  selected_note jsonb,
  note_issued_at timestamptz,
  exposure_note_hash text,
  exposure_client_reported_at timestamptz,
  exposure_acknowledged_at timestamptz,
  exposure_acknowledgement_source text check (exposure_acknowledgement_source in ('exposure_endpoint', 'final_payload')),
  final_brand text check (final_brand in ('charitea_mate_can', 'oom_balance')),
  switched boolean,
  story_delta integer check (story_delta in (10, -10)),
  abort_reason text check (abort_reason in ('user_left', 'no_eligible_move', 'technical_error', 'expired')),
  unique (session_id, round_index),
  check (final_brand is null or initial_brand is not null),
  check (target_brand is null or initial_brand is not null),
  check (phase <> 'finished' or (final_brand is not null and switched is not null and story_delta is not null)),
  check (phase <> 'aborted' or abort_reason is not null)
);

create unique index om_one_active_round_per_session
  on public.om_rounds(session_id)
  where phase in ('choosing', 'preparing_move', 'awaiting_rechoice');

create table public.om_commands (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.om_sessions(id) on delete restrict,
  round_id uuid not null references public.om_rounds(id) on delete restrict,
  result_round_id uuid references public.om_rounds(id) on delete restrict,
  command_id uuid not null,
  action text not null,
  request_hash text not null,
