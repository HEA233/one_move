  if round_row.phase <> 'preparing_move' then raise exception 'conflict' using errcode = 'P0001'; end if;

  if p_plan->'note' is null or jsonb_typeof(p_plan->'note') = 'null' then
    update public.om_rounds set phase = 'aborted', abort_reason = 'no_eligible_move', ended_at = now(), revision = revision + 1, updated_at = now() where id = p_round_id;
  else
    update public.om_rounds set
      selector_origin = p_plan->>'selectorOrigin',
      selection_probability = nullif(p_plan->>'selectionProbability', '')::numeric,
      model_id = p_plan->>'modelId',
      prompt_version = p_plan->>'promptVersion',
      selected_note = p_plan->'note',
      note_issued_at = now(),
      phase = 'awaiting_rechoice',
      revision = revision + 1,
      updated_at = now()
    where id = p_round_id;
  end if;

  insert into public.om_commands(session_id, round_id, command_id, action, request_hash) values (p_session_id, p_round_id, p_command_id, 'ensure_move', p_request_hash);
  select * into round_row from public.om_rounds where id = p_round_id;
  return jsonb_build_object('round', to_jsonb(round_row), 'replayed', false, 'command_id', p_command_id);
